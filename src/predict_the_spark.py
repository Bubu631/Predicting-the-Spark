"""## 2.10 C_index (Composite Flammability Index) Explanation

After computing the proportion \( p_k \) of each fuel type within a grid cell, we weight these proportions by their corresponding flammability levels to obtain the composite flammability index \( C_index):
$$
C_{\text{index}}= \sum_k p_k(\text{cell}) \cdot \text{flammability}(k)
$$
Where:

- C_index represents the area proportion of fuel type \( k \) within the cell.
- flammability(k) is the flammability level assigned to fuel type \( k \) (ranging from 1 to 5).
- k  indexes all fuel types.

This means that if a grid cell contains a larger proportion of high-flammability fuels, the value of C_index will be higher. Conversely, if the cell is dominated by low-flammability or non-burnable fuels, the index will be lower.

Therefore, the C_index essentially reflects the **overall potential fire intensity** of each grid cell.

## 2.11 Calculating the Proportion \(p_k\) for Each Fuel Type

In the downsampled raster, we first extract the fuel model values from all valid cells and count the occurrences of each fuel type across the region. By dividing the number of cells of a given fuel type by the total number of valid cells, we obtain its area proportion \(p_k\) within the study area.

A total proportion close to 100% indicates that the data distribution is consistent and reliable.
"""

# Get valid pixels and flatten to 1D
valid = np.isfinite(small)
vals_small = small[valid].astype(np.int32)

# Count class occurrences and compute proportions
uniq, cnts = np.unique(vals_small, return_counts=True)
p_df = pd.DataFrame({"FBFM40_class": uniq, "count": cnts})
p_df["p_k"] = p_df["count"] / p_df["count"].sum()

print("Σ p_k =", p_df["p_k"].sum())
p_df = p_df.sort_values("FBFM40_class")

"""## 2.12 Generate Fishnet Grid
Generate a 10 km fishnet grid and compute grid-level pₖ. Aggregate the high-resolution fuel raster to a uniform cell size to obtain each cell’s fuel composition.

This provides the spatial unit foundation for computing the composite flammability index C_index.

"""

# small: low-res raster (H, W) with values -9999 or 91..204
# scale: downsample factor (e.g., 8 or 4)
base_pixel_m = 250
cell_size_m  = 10000     # 10 km cells
nodata_val   = -9999

# Precompute tiling and grid shape
pixel_m = base_pixel_m * scale
tile    = max(1, int(round(cell_size_m / pixel_m)))
H, W    = small.shape
ncols   = (W + tile - 1) // tile

print(f"tile={tile}, ncols={ncols}, cells≈{((H+tile-1)//tile)*ncols}")

# Build masks and cell ids (fully vectorized)
valid = np.isfinite(small) & (small != nodata_val)
vals  = small[valid].astype(int)

# Keep only 91..204 to be safe
keep  = (vals >= 91) & (vals <= 204)
vals  = vals[keep]
if vals.size == 0:
    raise ValueError("No valid pixels. Check nodata, AOI, or cell_size_m/scale.")

rr, cc = np.nonzero(valid)
rr = rr[keep];  cc = cc[keep]
cell_r = rr // tile
cell_c = cc // tile
cid    = (cell_r * ncols + cell_c).astype(np.int64)

#  Aggregate with pandas: pixel counts per (cell_id, class)
df = pd.DataFrame({"cell_id": cid, "code": vals})
counts = (
    df.value_counts(["cell_id", "code"])
      .rename("cnt")
      .reset_index()
)

# Wide table: rows = cells, cols = classes
wide = counts.pivot(index="cell_id", columns="code", values="cnt").fillna(0).astype(np.uint32)

# Class proportions p_k per cell
den = wide.sum(axis=1).replace(0, 1)   # avoid div-by-zero
pk  = (wide.T / den).T                 # (cells × C)

# Recover grid row/col
row = (pk.index.values // ncols).astype(int)
col = (pk.index.values %  ncols).astype(int)

grid_pk_df = (
    pk.reset_index()
      .rename_axis(None, axis=1)
      .assign(row=row, col=col, total_pix=den.values.astype(int))
      .reindex(columns=["cell_id", "row", "col", "total_pix"] + [c for c in pk.columns])
      .sort_values(["row","col"])
      .reset_index(drop=True)
)

# Sanity check: sum_k p_k ≈ 1
max_dev = (grid_pk_df[pk.columns].sum(axis=1) - 1).abs().max()
print(f"Max |Σp_k-1| = {float(max_dev):.6f},  out_cells = {len(grid_pk_df)}")

# Feature matrix only (p_k by class)
feature_df = grid_pk_df[["cell_id"] + list(pk.columns)]

chunk = 500_000
n = len(grid_pk_df)
for i in range(0, n, chunk):
    grid_pk_df.iloc[i:i+chunk].to_parquet(
        f"/content/pk_5km_part_{i//chunk:03d}.parquet",
        index=False, compression="zstd"
    )

