"""## 2.4 Raster Data Loading and Downsampling

The original FBFM40 raster is provided at a resolution of 250m × 250m, which can be computationally expensive to process directly. To improve performance and reduce memory usage, we downsample the raster before analysis, scaling it down to 1/16 of its original size.
"""

import rasterio
from affine import Affine
from rasterio.enums import Resampling

scale = 16
with rasterio.open(tif_path) as src:
    T_orig = src.transform
    T_down = T_orig * Affine.scale(scale)
    out_h, out_w = src.height//scale, src.width//scale
    small = src.read(
        1,
        out_shape=(out_h, out_w),
        resampling=getattr(Resampling, "mode", Resampling.nearest)
    )
    nodata = src.nodata
    if nodata is not None:
        small = np.where(small==nodata, np.nan, small)

