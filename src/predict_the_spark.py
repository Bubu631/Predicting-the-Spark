best_lr = learning_rates[best_idx]
best_val_auc = val_auc_list[best_idx]

print("\n" + "-"*60)
print("Tuning Results:")
for lr, tr_auc, vl_auc in zip(learning_rates, train_auc_list, val_auc_list):
    print(f"lr={lr:.3f} | Train AUC={tr_auc:.4f} | Val AUC={vl_auc:.4f}")

print("\nBest learning_rate Selected:", best_lr)
